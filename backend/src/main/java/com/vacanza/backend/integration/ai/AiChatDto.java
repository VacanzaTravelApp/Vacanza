package com.vacanza.backend.integration.ai;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonProperty;
import com.vacanza.backend.dto.weather.DailyWeatherSummary;
import com.vacanza.backend.dto.weather.DayPartWeatherDay;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.Instant;
import java.util.List;
import java.util.UUID;

/**
 * DTOs for AI chat service proxy requests/responses.
 * AI service returns snake_case JSON.
 */
public final class AiChatDto {

    private AiChatDto() {}

    /** Request body for sending a message. */
    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class MessageSendRequest {
        private String content;
    }

    /** Response when creating a conversation. */
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    public static class ConversationCreateResponse {
        private UUID id;
    }

    /** Conversation item in list response. */
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    public static class ConversationListItem {
        private UUID id;
        @JsonProperty("created_at")
        private Instant createdAt;
        @JsonProperty("updated_at")
        private Instant updatedAt;
        @JsonProperty("user_id")
        private UUID userId;
        private String title;
    }

    /** Single message in history. */
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    public static class MessageItem {
        private UUID id;
        private String role;
        private String content;
        @JsonProperty("created_at")
        private Instant createdAt;
    }

    /** AI response when sending a message. */
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    public static class MessageSendResponse {
        private String content;

        @JsonProperty("extracted_preferences")
        private List<ExtractedPreference> extractedPreferences;

        @JsonProperty("route_data")
        private RouteData routeData;

        /** Short contextual message about the route (e.g. "Müzeleri sevdiğini biliyordum, o yüzden rotanda ağırlıklı olarak müzeler var."). */
        @JsonProperty("route_summary_message")
        private String routeSummaryMessage;

        /**
         * Persisted {@code ai_routes.route_id} after this turn saved route JSON (Java-only).
         */
        @JsonProperty("route_id")
        private UUID routeId;

        /**
         * Set by Java when the response is tied to a known conversation (e.g. map polygon route flow).
         * Not returned by the Python AI service for normal chat sends.
         */
        @JsonProperty("conversation_id")
        private UUID conversationId;
    }

    /** A single stop/place in a day's route plan. */
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class RouteWaypoint {
        private String name;
        private String description;
        private String category;
        private int day;
        private int order;
        private Double latitude;
        private Double longitude;

        @JsonProperty("estimated_duration_min")
        private Integer estimatedDurationMin;

        @JsonProperty("time_slot")
        private String timeSlot;

        /** Minutes walking from previous stop; null for the first stop of the day. */
        @JsonProperty("travel_from_previous_min")
        private Integer travelFromPreviousMin;

        @JsonProperty("arrival_time_local")
        private String arrivalTimeLocal;

        @JsonProperty("departure_time_local")
        private String departureTimeLocal;

        /**
         * Set to {@code true} by adaptive adjustment when this stop is known to be
         * closed or inaccessible. The frontend should render it with a visual indicator
         * rather than removing it from the map, allowing users to see what was affected.
         */
        private Boolean unavailable;
    }

    /** One day's itinerary within a multi-day route. */
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class DayPlan {
        private int day;
        private String title;
        private List<RouteWaypoint> waypoints;

        @JsonProperty("day_start_local")
        private String dayStartLocal;

        @JsonProperty("day_end_local")
        private String dayEndLocal;
    }

    /** Complete multi-day travel route generated by AI. */
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class RouteData {
        private String title;
        private String destination;

        @JsonProperty("total_days")
        private int totalDays;

        /**
         * When {@code true}, event search uses the trip date range from weather/route (narrow). When {@code false}
         * or {@code null}/omitted, search uses a ~30-day window from today (broad).
         */
        @JsonProperty("trip_dates_user_specified")
        private Boolean tripDatesUserSpecified;

        /**
         * First calendar day of the trip when the user stated dates (ISO {@code YYYY-MM-DD}). Takes precedence over
         * weather for event search and itinerary alignment.
         */
        @JsonProperty("trip_start_date")
        private String tripStartDate;

        private List<DayPlan> days;
        private String notes;

        /** Open-Meteo daily summaries; set by backend after POI+weather flow. */
        @JsonProperty("weather_forecast")
        private List<DailyWeatherSummary> weatherForecast;

        /** Morning/afternoon/evening slots from hourly forecast; set by backend with POI+weather flow. */
        @JsonProperty("weather_day_parts")
        private List<DayPartWeatherDay> weatherDayParts;
    }

    /** A single preference extracted by AI from the conversation. */
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    public static class ExtractedPreference {
        @JsonProperty("preference_key")
        private String preferenceKey;

        @JsonProperty("preference_value")
        private String preferenceValue;

        private Double confidence;
    }

    /** POST /events/recommend-for-route — AI ranking and personalized message. */
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class DaySummaryAi {
        private int day;
        private String title;
        private List<String> categories;
    }

    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class RouteSummaryForRecommend {
        private String destination;

        @JsonProperty("total_days")
        private int totalDays;

        @JsonProperty("start_date")
        private String startDate;

        @JsonProperty("day_summaries")
        private List<DaySummaryAi> daySummaries;
    }

    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class UserPreferenceSummaryAi {
        @JsonProperty("travel_style")
        private String travelStyle;

        @JsonProperty("favorite_categories")
        private List<String> favoriteCategories;

        @JsonProperty("event_interest")
        private String eventInterest;

        @JsonProperty("preferred_language")
        private String preferredLanguage;
    }

    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class AvailableEventAi {
        private String id;
        private String name;
        private String description;

        @JsonProperty("start_time")
        private String startTime;

        @JsonProperty("end_time")
        private String endTime;

        @JsonProperty("venue_name")
        private String venueName;
        private String category;
        private Double latitude;
        private Double longitude;
    }

    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class EventRecommendAiRequest {
        @JsonProperty("route_summary")
        private RouteSummaryForRecommend routeSummary;

        @JsonProperty("user_preferences")
        private UserPreferenceSummaryAi userPreferences;

        @JsonProperty("available_events")
        private List<AvailableEventAi> availableEvents;
    }

    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class RecommendedEventResultAi {
        @JsonProperty("event_id")
        private String eventId;

        @JsonProperty("matched_day")
        private Integer matchedDay;

        @JsonProperty("match_reason")
        private String matchReason;

        @JsonProperty("relevance_score")
        private Double relevanceScore;
    }

    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class EventRecommendAiResponse {
        private String message;

        @JsonProperty("recommended_events")
        private List<RecommendedEventResultAi> recommendedEvents;
    }
}
